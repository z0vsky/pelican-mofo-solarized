"""Generate a Pygments stylesheet whose text colours meet WCAG AA contrast.

Usage: python tools/code_css.py solarized-light > static/css/code-light.css
       python tools/code_css.py solarized-light --original > static/css/code-light-solarized.css

Solarized's accent colours are below the 4.5:1 contrast that WCAG AA asks
for normal text. Each text colour is moved towards black (on a light
background) or white (on a dark one) just far enough to reach the target,
so it keeps its hue. Background colours are left unchanged.
With --original, the Pygments colours are kept as they are.
"""

import re
import sys

from pygments.formatters import HtmlFormatter
from pygments.styles import get_style_by_name

TARGET = 4.6  # WCAG AA is 4.5:1; a small margin absorbs rounding


def rgb(hex_color):
    hex_color = hex_color.lstrip("#")
    return tuple(int(hex_color[i : i + 2], 16) for i in (0, 2, 4))


def luminance(color):
    channels = [c / 255 for c in color]
    channels = [c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4 for c in channels]
    return 0.2126 * channels[0] + 0.7152 * channels[1] + 0.0722 * channels[2]


def contrast(a, b):
    high, low = sorted((luminance(a), luminance(b)), reverse=True)
    return (high + 0.05) / (low + 0.05)


def adjust(color, background):
    """Mix color towards black or white until it reaches TARGET contrast."""
    toward = (0, 0, 0) if luminance(background) > 0.5 else (255, 255, 255)
    mixed = color
    step = 0
    while contrast(mixed, background) < TARGET and step < 100:
        step += 1
        mixed = tuple(round(c + (t - c) * step / 100) for c, t in zip(color, toward))
    return "#%02x%02x%02x" % mixed


def main(style_name, original=False):
    style = get_style_by_name(style_name)
    background = rgb(style.background_color)
    css = HtmlFormatter(style=style).get_style_defs(".highlight")

    if original:
        print(
            f"/* Generated by `make css` from the Pygments style '{style_name}', unchanged.\n"
            "   Several colours are below WCAG AA contrast. Do not edit by hand. */"
        )
        print(css)
        return

    # Only "color:", not "background-color:".
    def replace(match):
        return "color: " + adjust(rgb(match.group(1)), background)

    css = re.sub(r"(?<![-\w])color: (#[0-9a-fA-F]{6})", replace, css)
    print(
        f"/* Generated by `make css` from the Pygments style '{style_name}', with text\n"
        f"   colours adjusted to at least {TARGET}:1 contrast (WCAG AA). Do not edit by hand. */"
    )
    print(css)


if __name__ == "__main__":
    main(sys.argv[1], original="--original" in sys.argv[2:])
